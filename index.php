  <!-- 4. Knit Tech & 200-Needle Engineering -->
  <section class="section-padding bg-white" id="knit-tech">
    <div class="container">
      <div class="grid-2">
        <div>
          <span class="section-subtitle">Textile Engineering</span>
          <h2>The Anatomy of 200-Needle Seamless Circular Knitting</h2>
          <p>Most commercial socks are knitted on standard 96-needle or 144-needle industrial machines using coarse synthetic yarns, producing loose knit structures that pill, sag, and develop holes within months.</p>
          <p>At <strong>Bamboo Knit Reef</strong>, we utilize high-density 200-needle Lonati circular knitting cylinders from Brescia, Italy. By packing 200 micro-needles into a standard 3.75-inch cylinder diameter, we produce an ultra-dense, silky knit that resists pilling, hugs the contours of the foot like a second skin, and retains its shape wash after wash.</p>
          <div class="eco-callout">
            <p><strong>Hand-Linked Seamless Toes:</strong> Automated sock factories close the toe with a bulky overlock sewing machine stitch that rubs against the top of the toes. Our socks are hand-linked loop-by-loop with fine nylon thread, creating a completely flat, imperceptible seam.</p>
          </div>
        </div>
